drop function if exists public.create_order(text,text,text,text,text,text,text);

create or replace function public.create_order(
  p_name text,
  p_phone text,
  p_governorate text,
  p_city text,
  p_address text,
  p_landmark text default null,
  p_payment text default 'cash'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_order uuid;
  v_number text;
  v_subtotal numeric(12,2);
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  if length(trim(coalesce(p_name,''))) < 2 or length(p_name) > 100 then raise exception 'Invalid customer name'; end if;
  if p_phone !~ '^[0-9+() .-]{8,20}$' then raise exception 'Invalid phone number'; end if;
  if length(trim(coalesce(p_governorate,''))) < 2 or length(p_governorate) > 100 then raise exception 'Invalid governorate'; end if;
  if length(trim(coalesce(p_city,''))) < 2 or length(p_city) > 100 then raise exception 'Invalid city'; end if;
  if length(trim(coalesce(p_address,''))) < 5 or length(p_address) > 300 then raise exception 'Invalid address'; end if;
  if p_landmark is not null and length(p_landmark) > 200 then raise exception 'Invalid landmark'; end if;
  if p_payment <> 'cash' then raise exception 'Only cash payment is currently available'; end if;
  if not exists (select 1 from cart_items where user_id = v_user) then raise exception 'Cart is empty'; end if;

  perform p.id
  from products p
  join cart_items c on c.product_id = p.id
  where c.user_id = v_user
  for update;

  if exists (
    select 1 from cart_items c
    join products p on p.id = c.product_id
    where c.user_id = v_user and (p.active = false or c.quantity > p.stock_quantity)
  ) then
    raise exception 'One or more products are out of stock or have insufficient stock';
  end if;

  select coalesce(sum(c.quantity * p.price),0) into v_subtotal
  from cart_items c join products p on p.id=c.product_id
  where c.user_id=v_user and p.active=true;

  if v_subtotal <= 0 then raise exception 'Cart has no valid products'; end if;

  v_number := 'FL-' || to_char(now(),'YYMMDD') || '-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));

  insert into orders(user_id,order_number,payment,customer_name,customer_email,phone,governorate,city,address,landmark,subtotal,shipping,total)
  values(v_user,v_number,p_payment,trim(p_name),nullif(lower(trim(coalesce(auth.jwt()->>'email',''))),''),trim(p_phone),trim(p_governorate),trim(p_city),trim(p_address),nullif(trim(coalesce(p_landmark,'')),''),v_subtotal,0,v_subtotal)
  returning id into v_order;

  insert into order_items(order_id,product_id,product_name,category,color_name,image_path,unit_price,quantity,line_total)
  select v_order,p.id,p.name,p.category,p.color_name,p.image_path,p.price,c.quantity,p.price*c.quantity
  from cart_items c join products p on p.id=c.product_id
  where c.user_id=v_user and p.active=true;

  update products p
  set stock_quantity = p.stock_quantity - c.quantity
  from cart_items c
  where c.user_id = v_user and p.id = c.product_id;

  delete from cart_items where user_id=v_user;

  return jsonb_build_object('order_id',v_order,'order_number',v_number,'total',v_subtotal);
end;
$$;

revoke all on function public.create_order(text,text,text,text,text,text,text) from public, anon, authenticated;
grant execute on function public.create_order(text,text,text,text,text,text,text) to authenticated;

-- =========================================================
-- 9) Atomic admin status transition + one-time stock restoration on cancellation
-- Called only by the service-role-backed Edge Function.
-- =========================================================
create or replace function public.admin_set_order_status(p_order_id uuid, p_status text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_allowed boolean := false;
  v_stock_restored boolean := false;
begin
  if auth.role() <> 'service_role' then raise exception 'Not authorized'; end if;
  if p_status not in ('pending','confirmed','preparing','shipping','delivered','cancelled') then
    raise exception 'Invalid order status';
  end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if v_order.status = p_status then
    return jsonb_build_object('changed', false, 'status', v_order.status, 'stock_restored', false, 'order', to_jsonb(v_order));
  end if;
  v_allowed := case v_order.status
    when 'pending' then p_status in ('confirmed','cancelled')
    when 'confirmed' then p_status in ('preparing','cancelled')
    when 'preparing' then p_status in ('shipping','cancelled')
    when 'shipping' then p_status = 'delivered'
    when 'delivered' then false
    when 'cancelled' then false
    else false end;
  if not v_allowed then raise exception 'Invalid order status transition'; end if;

  update public.orders set status = p_status where id = p_order_id returning * into v_order;
  if p_status = 'cancelled' then
    update public.products p
      set stock_quantity = p.stock_quantity + restored.qty
    from (
      select product_id, sum(quantity)::integer as qty
      from public.order_items
      where order_id = p_order_id and product_id is not null
      group by product_id
    ) restored
    where p.id = restored.product_id;
    v_stock_restored := true;
  end if;
  return jsonb_build_object('changed', true, 'status', p_status, 'stock_restored', v_stock_restored, 'order', to_jsonb(v_order));
end;
$$;
revoke all on function public.admin_set_order_status(uuid,text) from public, anon, authenticated;
grant execute on function public.admin_set_order_status(uuid,text) to service_role;

